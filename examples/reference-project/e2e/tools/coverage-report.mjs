/**
 * The inventory: every case, where it lives, and whether it runs.
 *
 * Generated from `cases/` and `tests/` rather than maintained by hand, because
 * a coverage document that is written once is wrong within a week.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ID = /^\|\s*([A-Z]{3}-[A-Z0-9]{2,6}-\d{3}[a-z]?)(\s+SKIP)?\s*\|\s*([^|]+?)\s*\|/;

function walk(dir, match) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) out.push(...walk(path, match));
    else if (match.test(entry)) out.push(path);
  }
  return out;
}

const scripted = new Set();
for (const file of walk('tests', /\.ts$/)) {
  for (const [, id] of readFileSync(file, 'utf8').matchAll(/\b([A-Z]{3}-[A-Z0-9]{2,6}-\d{3}[a-z]?)\b/g)) {
    scripted.add(id);
  }
}

const files = walk('cases', /\.md$/).filter((f) => !f.endsWith('README.md')).sort();
const lines = ['# Coverage', '', 'Generated by `pnpm coverage`. Do not edit by hand.', ''];
let total = 0;
let automated = 0;

for (const file of files) {
  const rows = [];
  let title = file;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (line.startsWith('# ')) title = line.slice(2).trim();
    const m = ID.exec(line);
    if (m === null) continue;
    const [, id, , name] = m;
    const runs = scripted.has(id);
    total += 1;
    if (runs) automated += 1;
    rows.push(`| ${runs ? '✅' : '⬜'} | \`${id}\` | ${name} |`);
  }
  if (rows.length === 0) continue;
  lines.push(`## ${title}`, '', `\`${file}\` — ${rows.filter((r) => r.includes('✅')).length} of ${rows.length} automated`, '', '| | ID | Case |', '|---|---|---|', ...rows, '');
}

lines.splice(3, 0, `**${automated} of ${total} cases automated.** ✅ runs today, ⬜ is written down and waiting on a fixture.`, '');
writeFileSync('COVERAGE.md', lines.join('\n'));
console.log(`${automated} of ${total} automated across ${files.length} case files`);
