#!/usr/bin/env bash
# Bring up the ISOLATED end-to-end stack and make it serve: containers, then
# migrations, then seeds. Idempotent — safe to re-run.
#
#   pnpm e2e:up
#
# It owns `.env.e2e`, which is GENERATED rather than tracked. One owner for the
# ports (this file), so the compose file and the env file cannot drift into
# pointing at different things — which is the failure that makes an "isolated"
# stack quietly talk to the shared one.
set -euo pipefail

cd "$(dirname "$0")/.."

# ONE OFFSET, EVERY PORT, AND THE ENV FILE — derived here so the compose file
# and the env file cannot disagree about which stack they mean.
#
#   pnpm e2e:up                                     the default isolated stack
#   E2E_PROJECT=app-mine E2E_PORT_OFFSET=200 pnpm e2e:up    one of your own
#
# WHY AN OFFSET AND NOT A SECOND COMPOSE FILE. Several sessions work in this
# repo at once and more than one points at the default isolated stack; their
# workers then long-poll the same queue and eat each other's jobs, which looks
# like a job that never ran rather than like contention. A copied compose file
# would have to be kept in step with this one forever; an offset cannot drift.
#
# Offsets are in hundreds by convention: the shared stack owns 5xx32/5xx79/59xxx,
# this one at offset 0 sits directly above it, and yours goes above that. A
# collision means somebody else is already using your offset — pick another.
export E2E_PROJECT="${E2E_PROJECT:-app-e2e}"
OFFSET="${E2E_PORT_OFFSET:-0}"

export E2E_PG_PORT=$((55532 + OFFSET))
export E2E_PGB_PORT=$((56532 + OFFSET))
export E2E_VALKEY_PORT=$((56479 + OFFSET))
export E2E_SQS_PORT=$((59424 + OFFSET))
export E2E_SQS_UI_PORT=$((59425 + OFFSET))
export E2E_S3_PORT=$((59100 + OFFSET))
export E2E_S3_UI_PORT=$((59101 + OFFSET))
export E2E_SMTP_PORT=$((51125 + OFFSET))
export E2E_MAIL_UI_PORT=$((58125 + OFFSET))
# The API port moves too. Two stacks are no use if both APIs want 3100.
API_PORT=$((3100 + OFFSET))

COMPOSE="docker compose -f docker-compose.e2e.yml"
# `.env.e2e` for the default stack, so nothing that already refers to it breaks;
# `.env.<project>` for anything else.
ENV_FILE=".env.e2e"
[ "$E2E_PROJECT" != "app-e2e" ] && ENV_FILE=".env.${E2E_PROJECT}"

# --- the env file, regenerated every run so it always matches the compose file
cat > "$ENV_FILE" <<ENV
# GENERATED by scripts/e2e-up.sh. Do not edit — your changes are overwritten.
# Project ${E2E_PROJECT}, port offset ${OFFSET}. See docker-compose.e2e.yml.
NODE_ENV=dev
PORT=${API_PORT}
CENTRAL_DATABASE_URL=postgres://postgres:postgres@localhost:${E2E_PGB_PORT}/app_central
LOCAL_TENANT_DB_USER=postgres
LOCAL_TENANT_DB_PASSWORD=postgres
# THE ISOLATION-CRITICAL PAIR. Tenant databases are reached through THIS
# stack's PgBouncer. Point these at 56432 and the fan-out migrates the shared
# stack's tenants while everything else here talks to the isolated one.
LOCAL_TENANT_DB_HOST=localhost
LOCAL_TENANT_DB_PORT=${E2E_PGB_PORT}
MAX_LIVE_TENANT_POOLS=10
TENANT_POOL_MAX=2
CENTRAL_POOL_MAX=10
VALKEY_URL=redis://localhost:${E2E_VALKEY_PORT}
SQS_ENDPOINT=http://localhost:${E2E_SQS_PORT}
SQS_QUEUE_INTERACTIVE=http://localhost:9324/000000000000/app-local-interactive
SQS_QUEUE_BULK=http://localhost:9324/000000000000/app-local-bulk
SQS_QUEUE_MAINTENANCE=http://localhost:9324/000000000000/app-local-maintenance
QUEUE_CLASS=interactive
AWS_REGION=ap-south-1
S3_BUCKET=app-e2e-files
S3_ENDPOINT=http://localhost:${E2E_S3_PORT}
SMTP_HOST=localhost
SMTP_PORT=${E2E_SMTP_PORT}
SMTP_FROM=the reference project E2E <no-reply@app.local>
DEFAULT_LOCALE=en-US
AWS_ACCESS_KEY_ID=minioadmin
AWS_SECRET_ACCESS_KEY=minioadmin
# THE ISOLATED STACK HAS NO SECRETS MANAGER, and the default is `aws`.
# Without this the provisioning saga fails on its FIRST step with "The security
# token included in the request is invalid" — an AWS error, from a stack that
# has no AWS, on a step that was trying to mint a tenant credential. Every other
# local-only mode is already spelled out here; this one was missing, which is
# why building a workspace through the portal had never run locally.
TENANT_SECRETS_MODE=local
INTEGRATION_CRYPTO_MODE=local
LOCAL_INTEGRATION_KEY=e2e-local-integration-key-not-a-secret
ENV

echo "--- containers ---"
$COMPOSE up -d

# `up -d` returns when containers are STARTED, which is not the same as ready.
# Postgres in particular accepts a socket well before it will accept a query.
echo "--- waiting for health ---"
for svc in postgres pgbouncer valkey sqs s3; do
  printf '    %-10s' "$svc"
  for _ in $(seq 1 60); do
    state=$($COMPOSE ps --format '{{.Service}} {{.Health}}' 2>/dev/null | awk -v s="$svc" '$1==s {print $2}')
    [ "$state" = "healthy" ] && break
    sleep 2
  done
  [ "$state" = "healthy" ] || { echo "NOT healthy ($state)"; $COMPOSE logs --tail 30 "$svc"; exit 1; }
  echo "healthy"
done

echo "--- schema ---"
export ENV_FILE
pnpm migrate:central
pnpm seed:catalog
pnpm seed:integrations
pnpm seed:geography
pnpm seed:templates
pnpm seed:platform
pnpm seed:tenants
pnpm migrate:tenants
pnpm seed
# The seed writes matched loans directly, not through the hooked write paths,
# so the P&L rollup starts empty until it is rebuilt from source.
pnpm pnl:rebuild
pnpm setup:tenant-integrations
pnpm migrate:aon-grants
pnpm migrate:aos-grant
pnpm migrate:sidebar-read
pnpm migrate:pnl-grants

echo
echo "stack ${E2E_PROJECT} ready. Every command against it needs ENV_FILE=${ENV_FILE}:"
echo "    ENV_FILE=${ENV_FILE} pnpm start:api        (listens on ${API_PORT})"
echo "    ENV_FILE=${ENV_FILE} pnpm test:integration"
echo "  postgres  localhost:${E2E_PGB_PORT}     valkey  localhost:${E2E_VALKEY_PORT}"
echo "  sqs       localhost:${E2E_SQS_PORT}     s3      localhost:${E2E_S3_PORT}  (console :${E2E_S3_UI_PORT})"
echo "  mail UI   http://localhost:${E2E_MAIL_UI_PORT}"
